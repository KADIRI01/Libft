#include "libft.h"

size_t	ft_strlcat(char *dst, const char *src, size_t dstsize)
{
	size_t	i;
	size_t	len;

	i = 0;
	if (!dst && dstsize == 0)
		return (ft_strlen(src));
	len = ft_strlen(dst);
	if (len >= dstsize)
		return (ft_strlen(src) + dstsize);
	while (src[i] && len + i < dstsize - 1)
	{
		dst[len + i] = src[i];
		i++;
	}
	dst[len + i] = '\0';
	return (ft_strlen(src) + len);
}
